// A 3x5 pixel font for signage inside the pixel world (never for the film's own type, which is Dela / JetBrains).
const G = {
  A: '010101111101101', B: '110101110101110', C: '011100100100011', D: '110101101101110', E: '111100110100111',
  F: '111100110100100', G: '011100101101011', H: '101101111101101', I: '111010010010111', K: '101101110101101',
  L: '100100100100111', M: '101111111101101', N: '110101101101101', O: '010101101101010', P: '110101110100100',
  R: '110101110101101', S: '011100010001110', T: '111010010010010', U: '101101101101111', V: '101101101101010',
  W: '101101111111101', X: '101101010101101', Y: '101101010010010', Z: '111001010100111',
  0: '111101101101111', 1: '010110010010111', 2: '110001010100111', 3: '110001010001110', 4: '101101111001001',
  5: '111100110001110', 6: '011100111101111', 7: '111001010010010', 8: '111101111101111', 9: '111101111001110',
  '.': '000000000000010', '/': '001001010100100', '-': '000000111000000', ':': '000010000010000', '+': '000010111010000',
  '%': '101001010100101', '!': '010010010000010', '?': '110001010000010', ' ': '000000000000000', '$': '011110010011110',
};
export function pixText(c, str, x, y, col, s = 1, track = 1) {
  c.fillStyle = col;
  let cx = Math.round(x);
  for (const ch of str.toUpperCase()) {
    const g = G[ch] || G[' '];
    for (let i = 0; i < 15; i++) if (g[i] === '1') c.fillRect(cx + (i % 3) * s, Math.round(y) + Math.floor(i / 3) * s, s, s);
    cx += (3 + track) * s;
  }
  return cx - x;
}
export const pixWidth = (str, s = 1, track = 1) => str.length * (3 + track) * s - track * s;
